/* Cuts the square GPI/Vienna Insurance Group tree emblem out of the official
   horizontal logo lockup and writes src/assets/gpi-mark.svg — the compact mark
   for avatars, where the full lockup is illegible.

   Hand-run:  node scripts/build-gpi-mark.mjs

   Source of truth = prototype/reference/brand/"GPI Logo - ENG (color).svg" (the
   official Illustrator export the user supplied, a 1920×1080 artboard holding the
   "GPI" wordmark + tree emblem + red rule + VIENNA INSURANCE GROUP tagline). It
   lives INSIDE the repo on purpose — the project-root reference/ folder is outside
   git, so a script pointing there would break on a fresh clone.

   How the emblem is identified: the artboard has 8 <path>s and NO transforms.
   The four gradient-filled ones are the emblem (verified by measuring getBBox()
   in a browser: they cluster at x 1249–1758, y 190–639); the other four are the
   solid-navy wordmark and the tagline block.

   Two things must not be "optimised":
   · the gradients are gradientUnits="userSpaceOnUse" with absolute coordinates,
     so the ORIGINAL coordinate system is preserved and only the viewBox moves.
     Re-origin the paths and the fills slide off the artwork.
   · the emblem is sized to a FRACTION of a SQUARE viewBox so a circular avatar
     mask leaves visible padding around it. The ceiling is geometric: a square
     inscribed in a circle is only 1/√2 ≈ 0.707 of the diameter, so at 0.75 (the
     first attempt) the emblem's bbox corners sat exactly ON the arc and the tree
     looked like it was bursting out of the disc. At 0.62 those corners land at
     ~83% of the radius — real padding. Anything above ~0.70 will touch again. */
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'

const HERE = dirname(fileURLToPath(import.meta.url))
const SRC = join(HERE, '../reference/brand/GPI Logo - ENG (color).svg')
const OUT = join(HERE, '../src/assets/gpi-mark.svg')

/* Emblem bounding box in the artboard's own coordinates (measured, see above). */
const BBOX = { x: 1249, y: 190, w: 509, h: 449 }
const EMBLEM_FRACTION = 0.62 // keep ≤ ~0.70; see the note above

const src = readFileSync(SRC, 'utf8')
if (/transform=/.test(src)) {
  throw new Error('source now has transforms — the measured bbox is no longer valid in root coords')
}

const defs = src.match(/<defs>[\s\S]*?<\/defs>/)?.[0]
const paths = src.match(/<path[^>]*\/>/g) ?? []
if (!defs || paths.length !== 8) {
  throw new Error(`unexpected source shape: ${paths.length} paths, defs ${Boolean(defs)}`)
}
const emblem = paths.slice(0, 4)

const cx = BBOX.x + BBOX.w / 2
const cy = BBOX.y + BBOX.h / 2
const side = Math.round(BBOX.w / EMBLEM_FRACTION)
const viewBox = `${cx - side / 2} ${cy - side / 2} ${side} ${side}`

writeFileSync(
  OUT,
  `<?xml version="1.0" encoding="UTF-8"?>
<!-- GENERATED by scripts/build-gpi-mark.mjs — do not hand-edit.
     The GPI / Vienna Insurance Group tree emblem, cut from the official
     "GPI Logo - ENG (color).svg" lockup: only the four gradient-filled emblem
     paths are kept, and the viewBox is retargeted to a square centred on them
     with the emblem at ${EMBLEM_FRACTION * 100}% of the box, so a circular avatar mask leaves
     padding around it. Do not raise that past ~70%: a square inscribed in a
     circle is only 1/√2 of the diameter, so the emblem's corners would sit on
     (or outside) the arc. The gradients are userSpaceOnUse, so the
     original coordinate system is preserved verbatim — do NOT re-origin the
     path data or the fills will slide off the artwork. -->
<svg xmlns="http://www.w3.org/2000/svg" xmlns:xlink="http://www.w3.org/1999/xlink" viewBox="${viewBox}">${defs}${emblem.join(
    ''
  )}</svg>
`
)

console.log(`wrote ${OUT}\n  viewBox ${viewBox} · emblem ${EMBLEM_FRACTION * 100}% of box`)
